/**
 * generateReadMeToken
 *
 * Admin-only: Generate a time-limited signed token for sharing the DeveloperReadMe
 * with non-admin users (e.g., technical consultants, developers).
 *
 * Token format: base64url(payload_json).base64url(hmac_sha256_signature)
 * Payload: { iat, exp, purpose }
 * TTL: 24 hours by default (configurable)
 */
import { createClientFromRequest } from 'npm:@base44/sdk@0.8.25';

// Uses BASE44_APP_ID as default (always available). Optionally set README_TOKEN_SECRET for added security.
const TOKEN_SECRET = Deno.env.get('README_TOKEN_SECRET') || Deno.env.get('BASE44_APP_ID') || 'cc-readme-default-secret';
const TOKEN_TTL_HOURS = 24;

async function hmacSign(data, secret) {
  const encoder = new TextEncoder();
  const keyData = encoder.encode(secret);
  const msgData = encoder.encode(data);
  const cryptoKey = await crypto.subtle.importKey(
    'raw', keyData,
    { name: 'HMAC', hash: 'SHA-256' },
    false,
    ['sign']
  );
  const sig = await crypto.subtle.sign('HMAC', cryptoKey, msgData);
  const arr = Array.from(new Uint8Array(sig));
  return btoa(String.fromCharCode(...arr)).replace(/\+/g, '-').replace(/\//g, '_').replace(/=/g, '');
}

function b64url(str) {
  return btoa(str).replace(/\+/g, '-').replace(/\//g, '_').replace(/=/g, '');
}

Deno.serve(async (req) => {
  if (req.method !== 'POST') {
    return Response.json({ error: 'Method not allowed' }, { status: 405 });
  }

  try {
    const base44 = createClientFromRequest(req);
    const user = await base44.auth.me();
    if (!user) return Response.json({ error: 'Unauthorized' }, { status: 401 });

    // Admin only
    const profiles = await base44.asServiceRole.entities.UserProfile.filter({ user_id: user.email });
    const profile = profiles[0];
    if (!profile?.is_admin && user?.role !== 'admin') {
      return Response.json({ error: 'Admin access required' }, { status: 403 });
    }

    const now = Math.floor(Date.now() / 1000);
    const exp = now + (TOKEN_TTL_HOURS * 3600);

    const payload = {
      iat: now,
      exp,
      purpose: 'readme_access',
      issued_by: user.email,
    };

    const payloadB64 = b64url(JSON.stringify(payload));
    const signature = await hmacSign(payloadB64, TOKEN_SECRET);
    const token = `${payloadB64}.${signature}`;

    // Log that token was generated
    await base44.asServiceRole.entities.AdminActionLog.create({
      admin_user_id: user.email,
      target_type: 'System',
      target_id: 'DeveloperReadMe',
      action: 'readme_token_generated',
      reason: `Shareable ReadMe token generated by ${user.email}`,
      metadata_json: { expires_at: new Date(exp * 1000).toISOString(), timestamp: new Date().toISOString() },
    }).catch(() => {});

    return Response.json({
      token,
      expires_at: new Date(exp * 1000).toISOString(),
      ttl_hours: TOKEN_TTL_HOURS,
      share_url: `${req.headers.get('origin') || ''}/DeveloperReadMe?access_token=${token}`,
    });

  } catch (error) {
    return Response.json({ error: error.message }, { status: 500 });
  }
});