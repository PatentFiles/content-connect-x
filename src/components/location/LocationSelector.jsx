export default function LocationSelector({ value, onChange, className }) {
  const [selectedCountry, setSelectedCountry] = useState(value?.country || '');
  const [selectedState, setSelectedState] = useState(value?.state || '');
  const [selectedCity, setSelectedCity] = useState(value?.city || '');
  const [showOther, setShowOther] = useState(false);
  const [customCity, setCustomCity] = useState('');
  const queryClient = useQueryClient();

  const { data: user } = useQuery({
    queryKey: ['currentUser'],
    queryFn: () => base44.auth.me(),
  });

  const { data: customCities = [] } = useQuery({
    queryKey: ['customCities', selectedState],
    queryFn: () => base44.entities.CustomCity.filter({ state: selectedState, verified: true }),
    enabled: !!selectedState,
  });

  const addCustomCityMutation = useMutation({
    mutationFn: (cityData) => base44.entities.CustomCity.create(cityData),
    onSuccess: () => {
      queryClient.invalidateQueries(['customCities']);
    },
  });

  useEffect(() => {
    onChange({
      country: selectedCountry,
      state: selectedState,
      city: selectedCity,
    });
  }, [selectedCountry, selectedState, selectedCity]);

  const allCities = selectedCountry === 'US' && selectedState
    ? [
        ...(usCities[selectedState] || []),
        ...customCities.map(c => c.city_name)
      ].sort()
    : [];

  const cityOptions = [
    ...allCities.map(city => ({ value: city, label: city })),
    { value: '__other__', label: '+ Add Other City' }
  ];

  const handleCityChange = (e) => {
    const value = e.target.value;
    if (value === '__other__') {
      setShowOther(true);
      setSelectedCity('');
    } else {
      setShowOther(false);
      setSelectedCity(value);
    }
  };

  const handleCustomCitySubmit = () => {
    if (!customCity.trim() || !user) return;

    setSelectedCity(customCity.trim());
    setShowOther(false);

    addCustomCityMutation.mutate({
      state: selectedState,
      city_name: customCity.trim(),
      added_by: user.email,
      verified: false
    });

    setCustomCity('');
  };

  return (
    <div className={className}>
      <div className="grid gap-4">
        <CCSelect
          label="Country"
          options={countries}
          value={selectedCountry}
          onChange={(e) => {
            setSelectedCountry(e.target.value);
            setSelectedState('');
            setSelectedCity('');
            setShowOther(false);
          }}
          placeholder="Select country"
        />

        {selectedCountry === 'US' && (
          <CCSelect
            label="State"
            options={usStates}
            value={selectedState}
            onChange={(e) => {
              setSelectedState(e.target.value);
              setSelectedCity('');
              setShowOther(false);
            }}
            placeholder="Select state"
          />
        )}

        {selectedCountry === 'US' && selectedState ? (
          <>
            <CCSelect
              label="City"
              options={cityOptions}
              value={showOther ? '__other__' : selectedCity}
              onChange={handleCityChange}
              placeholder="Select city"
            />
            {showOther && (
              <div>
                <label className="block text-sm font-medium text-[#E8EEF9] mb-1.5">Enter City Name</label>
                <div className="flex gap-2">
                  <input
                    type="text"
                    placeholder="Enter city name"
                    value={customCity}
                    onChange={(e) => setCustomCity(e.target.value)}
                    onKeyDown={(e) => e.key === 'Enter' && handleCustomCitySubmit()}
                    className="flex-1 bg-[#121824] border border-[#263248] rounded-lg px-4 py-2.5 text-[#E8EEF9] placeholder-[#6B7A94] focus:outline-none focus:ring-2 focus:ring-[#4F8CFF]/50 transition-all duration-200"
                  />
                  <button
                    onClick={handleCustomCitySubmit}
                    className="px-4 py-2 bg-[#4F8CFF] text-white rounded-lg hover:bg-[#3A7AEE] transition-colors"
                  >
                    Add
                  </button>
                </div>
              </div>
            )}
          </>
        ) : selectedCountry && selectedCountry !== 'US' ? (
          <div>
            <label className="block text-sm font-medium text-[#E8EEF9] mb-1.5">City</label>
            <input
              type="text"
              placeholder="Enter city name"
              value={selectedCity}
              onChange={(e) => setSelectedCity(e.target.value)}
              className="w-full bg-[#121824] border border-[#263248] rounded-lg px-4 py-2.5 text-[#E8EEF9] placeholder-[#6B7A94] focus:outline-none focus:ring-2 focus:ring-[#4F8CFF]/50 transition-all duration-200"
            />
          </div>
        ) : null}
      </div>
    </div>
  );
}