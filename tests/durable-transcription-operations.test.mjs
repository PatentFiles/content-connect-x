 assert.match(ddl,/grant execute on function public\.ccx_transcription_claim\(integer\) to service_role/i);
 assert.match(cron,/ccx_runtime_ccx_transcription_worker_key/);
 assert.match(cron,/ccx_private_transcription_every_five_minutes/);
 assert.match(clean,/ccx_audio_transcripts/);
